export const articleBySlug = (slug: string) => articles.find(a => a.slug === slug)

/** Свежие сверху */
export const sortedArticles = [...articles].sort((a, b) => b.publishedAt.localeCompare(a.publishedAt))

export const articlesForService = (slug: string) => sortedArticles.filter(a => a.serviceSlugs.includes(slug))

/** Разметка из текста: ссылки и выделение не должны попадать в подсчёт слов */
const plain = (text: string) => text.replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').replace(/\*\*/g, '')

const blockText = (block: ArticleBlock): string[] => {
  switch (block.type) {
    case 'list': return block.items
    case 'table': return [...block.head, ...block.rows.flat()]
    case 'image': return [block.caption ?? '']
    default: return [block.text]
  }
}

export const wordCount = (article: Article) =>
  [...article.summary, ...article.body.flatMap(blockText), ...article.faq.flatMap(f => [f.q, f.a])]
    .map(plain)
    .join(' ')
    .split(/\s+/)
    .filter(Boolean)
    .length

/** Время чтения при скорости ~180 слов в минуту */
export const readingMinutes = (article: Article) => Math.max(1, Math.round(wordCount(article) / 180))

/** Оглавление строится из заголовков второго уровня */
export const tocFor = (article: Article) =>
  article.body.filter((b): b is Extract<ArticleBlock, { type: 'h2' }> => b.type === 'h2')
