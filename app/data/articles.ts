/**
 * Статьи раздела «Журнал».
 *
 * Текст хранится блоками, а не HTML: так оглавление, время чтения и объём
 * для микроразметки считаются из тех же данных, что и сама страница.
 * Внутри текста работают [ссылки](/путь) и **выделение** — их разбирает RichText.
 */

export type ArticleBlock =
  | { type: 'p', text: string }
  /** id — якорь для оглавления */
  | { type: 'h2', id: string, text: string }
  | { type: 'h3', text: string }
  | { type: 'list', items: string[], ordered?: boolean }
  | { type: 'table', head: string[], rows: string[][], caption?: string }
  | { type: 'image', src: string, alt: string, caption?: string }

export interface Article {
  slug: string
  /** H1 и headline в микроразметке */
  title: string
  /** Короткий вариант для карточки */
  cardTitle: string
  category: string
  /** Лид под заголовком и текст карточки */
  excerpt: string
  cover: string
  /** Социальная карточка 1200×630 */
  ogImage: string
  publishedAt: string
  updatedAt: string
  /** «Коротко» в начале статьи — готовый ответ для поиска и нейросетей */
  summary: string[]
  body: ArticleBlock[]
  faq: FaqItem[]
  keywords: string[]
  /** Услуги, на страницах которых статья показывается в «Статьях по теме» */
  serviceSlugs: string[]
  meta: { title: string, description: string }
}

const price = (id: string) => {
  const row = priceRows.find(r => r.id === id)!
  return `от ${row.from} и ${row.term}`
}

